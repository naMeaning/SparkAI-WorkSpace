import assert from "node:assert/strict";
import { canvasWheelViewport } from "../src/canvas-wheel.ts";
const v = { x: 40, y: -10, scale: 0.8 }, p = { x: 350, y: 280 };
const e = { deltaX: 0, deltaY: 40, deltaMode: 0, ctrlKey: false, metaKey: false, shiftKey: false };
const next = (event = e, mode: "zoom" | "pan" = "zoom") => canvasWheelViewport(v, event, p, 600, mode, 0.1, 3);
const z = next();
assert.ok(z.scale < v.scale);
for (const axis of ["x", "y"] as const) assert.ok(Math.abs((p[axis] - z[axis]) / z.scale - (p[axis] - v[axis]) / v.scale) < 1e-8, "world point stays under pointer");
assert.equal(next({ ...e, deltaMode: 1, deltaY: 2.5 }).scale, z.scale);
assert.equal(next({ ...e, deltaMode: 2, deltaY: 1 / 15 }).scale, z.scale);
assert.deepEqual(next({ ...e, deltaX: 10 }, "pan"), { x: 30, y: -50, scale: 0.8 });
assert.deepEqual(next({ ...e, shiftKey: true }), { x: 0, y: -10, scale: 0.8 });
assert.ok(next({ ...e, ctrlKey: true }, "pan").scale < 0.8);
assert.ok(next({ ...e, metaKey: true }, "pan").scale < 0.8);
assert.ok(next({ ...e, deltaY: 1 }).scale > next({ ...e, deltaY: 10 }).scale);
let cursor = v;
for (let i = 0; i < 100; i++) cursor = canvasWheelViewport(cursor, e, p, 600, "zoom", 0.1, 3);
assert.equal(cursor.scale, 0.1);
for (let i = 0; i < 100; i++) cursor = canvasWheelViewport(cursor, { ...e, deltaY: -200 }, p, 600, "zoom", 0.1, 3);
assert.equal(cursor.scale, 3);
console.log(JSON.stringify({ ok: true, anchor: true, units: true, explicitModes: true, continuous: true, limits: true }));
